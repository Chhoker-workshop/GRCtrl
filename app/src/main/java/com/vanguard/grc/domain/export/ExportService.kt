package com.vanguard.grc.domain.export

import android.content.Context
import android.content.Intent
import android.graphics.Color
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import android.net.Uri
import androidx.core.content.FileProvider
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

/**
 * Result of an export operation.
 */
sealed class ExportResult {
    data class Success(val uri: Uri, val fileName: String, val mimeType: String) : ExportResult()
    data class Failure(val reason: String) : ExportResult()
}

/**
 * Offline export of registers, assessment reports and review packs.
 *
 * Two formats are produced using platform APIs only:
 *  - CSV, written as UTF-8 with a BOM so spreadsheet applications render
 *    non-ASCII characters correctly.
 *  - PDF, produced with [PdfDocument] so no third-party rendering library is
 *    required and no additional permission is needed.
 */
class ExportService(private val context: Context) {

    private val timestamp = SimpleDateFormat("yyyyMMdd-HHmmss", Locale.US)
    private val readable = SimpleDateFormat("yyyy-MM-dd HH:mm", Locale.US)

    /** Page geometry constants shared by the renderer. */
    private val pageWidth = 595      // A4 at 72dpi
    private val pageHeight = 842
    private val margin = 48f
    private val contentWidth = pageWidth - margin * 2

    private fun exportDir(): File =
        File(context.filesDir, "exports").apply { if (!exists()) mkdirs() }

    // --- CSV ---------------------------------------------------------------------

    /**
     * Writes rows as CSV. The first row is treated as the header.
     */
    suspend fun exportCsv(
        fileName: String,
        headers: List<String>,
        rows: List<List<String>>,
        title: String = ""
    ): ExportResult = withContext(Dispatchers.IO) {
        try {
            val file = File(exportDir(), "$fileName-${timestamp.format(Date())}.csv")
            file.bufferedWriter().use { writer ->
                if (title.isNotBlank()) {
                    writer.write("# $title")
                    writer.write("\n")
                    writer.write("# Generated by GRC VANGUARD on ${readable.format(Date())}")
                    writer.write("\n")
                    writer.write("# Educational tool output. Verify against your own organisational records before use.\n")
                }
                writer.write("\uFEFF")
                writer.write(headers.joinToString(",") { escape(it) })
                writer.write("\n")
                rows.forEach { row ->
                    writer.write(row.joinToString(",") { escape(it) })
                    writer.write("\n")
                }
            }
            ExportResult.Success(uriFor(file), file.name, "text/csv")
        } catch (e: Exception) {
            ExportResult.Failure(e.message ?: "Unable to write CSV")
        }
    }

    private fun escape(value: String): String {
        val normalised = value.replace("\r\n", " ").replace('\n', ' ').replace('\r', ' ')
        return if (normalised.contains(',') || normalised.contains('"')) {
            "\"" + normalised.replace("\"", "\"\"") + "\""
        } else {
            normalised
        }
    }

    // --- PDF ---------------------------------------------------------------------

    data class PdfSection(
        val heading: String,
        val paragraphs: List<String> = emptyList(),
        val bullets: List<String> = emptyList(),
        val table: List<List<String>> = emptyList()
    )

    /**
     * Renders a simple, professional PDF report.
     */
    suspend fun exportPdf(
        fileName: String,
        title: String,
        subtitle: String = "",
        sections: List<PdfSection> = emptyList(),
        footerNote: String = "Educational output produced by GRC VANGUARD. Verify against your own organisational records before relying on it."
    ): ExportResult = withContext(Dispatchers.IO) {
        try {
            val document = PdfDocument()

            var pageNumber = 0
            var page: PdfDocument.Page? = null
            var y = margin
            var canvas = android.graphics.Canvas(android.graphics.Bitmap.createBitmap(1, 1, android.graphics.Bitmap.Config.ARGB_8888))

            fun startPage(isFirst: Boolean) {
                page?.let { document.finishPage(it) }
                pageNumber++
                val info = PdfDocument.PageInfo.Builder(pageWidth, pageHeight, pageNumber).create()
                page = document.startPage(info)
                canvas = page!!.canvas
                y = margin
                if (isFirst) {
                    drawCoverBlock(canvas, title, subtitle, contentWidth)
                    y = margin + 96f
                }
            }

            startPage(true)

            sections.forEach { section ->
                if (y > pageHeight - margin - 80) startPage(false)

                canvas.drawText(section.heading, margin, y + 12f, headingPaint)
                y += 34f

                section.paragraphs.forEach { paragraph ->
                    val lines = wrapText(paragraph, contentWidth, bodyPaint)
                    lines.forEach { line ->
                        if (y > pageHeight - margin - 40) startPage(false)
                        canvas.drawText(line, margin, y, bodyPaint)
                        y += 15f
                    }
                    y += 6f
                }

                section.bullets.forEach { bullet ->
                    val lines = wrapText(bullet, contentWidth - 14f, bodyPaint)
                    lines.forEachIndexed { index, line ->
                        if (y > pageHeight - margin - 40) startPage(false)
                        if (index == 0) canvas.drawText("\u2022", margin, y, bulletPaint)
                        canvas.drawText(line, margin + 14f, y, bodyPaint)
                        y += 15f
                    }
                    y += 3f
                }

                if (section.table.isNotEmpty()) {
                    val colWidth = contentWidth / section.table.first().size
                    section.table.forEachIndexed { rowIndex, row ->
                        if (y > pageHeight - margin - 40) startPage(false)
                        row.forEachIndexed { colIndex, cell ->
                            val text = if (rowIndex == 0) cell.uppercase() else cell
                            val paint = if (rowIndex == 0) tableHeaderPaint else bodyPaint
                            val lines = wrapText(text, colWidth - 8f, paint)
                            canvas.drawText(lines.firstOrNull() ?: "", margin + colIndex * colWidth, y, paint)
                        }
                        y += 16f
                    }
                    y += 10f
                }
                y += 10f
            }

            page?.let { document.finishPage(it) }

            val file = File(exportDir(), "$fileName-${timestamp.format(Date())}.pdf")
            file.outputStream().use { document.writeTo(it) }
            document.close()

            ExportResult.Success(uriFor(file), file.name, "application/pdf")
        } catch (e: Exception) {
            ExportResult.Failure(e.message ?: "Unable to write PDF")
        }
    }

    private fun drawCoverBlock(
        canvas: android.graphics.Canvas,
        title: String,
        subtitle: String,
        contentWidth: Float
    ) {
        canvas.drawRect(0f, 0f, contentWidth + 96f, 78f, coverBandPaint)
        canvas.drawText("GRC VANGUARD", margin, 34f, coverBrandPaint)
        canvas.drawText(title, margin, 60f, coverTitlePaint)
        if (subtitle.isNotBlank()) {
            canvas.drawText(subtitle, margin, 90f, subtitlePaint)
        }
    }

    private val coverBandPaint = android.graphics.Paint().apply {
        color = Color.rgb(11, 18, 32)
        isAntiAlias = true
    }
    private val coverBrandPaint = android.graphics.Paint().apply {
        color = Color.rgb(212, 175, 96)
        textSize = 11f
        typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
        letterSpacing = 0.18f
    }
    private val coverTitlePaint = android.graphics.Paint().apply {
        color = Color.WHITE
        textSize = 18f
        typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
    }
    private val subtitlePaint = android.graphics.Paint().apply {
        color = Color.rgb(110, 128, 150)
        textSize = 11f
    }
    private val headingPaint = android.graphics.Paint().apply {
        color = Color.rgb(19, 32, 54)
        textSize = 13f
        typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
    }
    private val bodyPaint = android.graphics.Paint().apply {
        color = Color.rgb(40, 49, 63)
        textSize = 10.5f
    }
    private val bulletPaint = android.graphics.Paint().apply {
        color = Color.rgb(190, 150, 69)
        textSize = 10.5f
    }
    private val tableHeaderPaint = android.graphics.Paint().apply {
        color = Color.rgb(19, 32, 54)
        textSize = 9.5f
        typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
    }

    private fun wrapText(text: String, maxWidth: Float, paint: android.graphics.Paint): List<String> {
        if (text.isBlank()) return listOf("")
        val words = text.split(" ")
        val lines = mutableListOf<String>()
        var current = StringBuilder()
        words.forEach { word ->
            val candidate = if (current.isEmpty()) word else "$current $word"
            if (paint.measureText(candidate) <= maxWidth) {
                current = StringBuilder(candidate)
            } else {
                if (current.isNotEmpty()) lines += current.toString()
                current = StringBuilder(word)
            }
        }
        if (current.isNotEmpty()) lines += current.toString()
        return lines
    }

    // --- Sharing -----------------------------------------------------------------

    private fun uriFor(file: File): Uri = FileProvider.getUriForFile(
        context,
        "${context.packageName}.fileprovider",
        file
    )

    /**
     * Builds a share intent for an exported artefact.
     */
    fun shareIntent(uri: Uri, mimeType: String): Intent =
        Intent(Intent.ACTION_SEND).apply {
            type = mimeType
            putExtra(Intent.EXTRA_STREAM, uri)
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }

    /**
     * Lists previously exported artefacts.
     */
    fun exportedFiles(): List<File> =
        exportDir().listFiles()?.sortedByDescending { it.lastModified() } ?: emptyList()

    fun deleteExport(file: File): Boolean = file.delete()

    suspend fun exportText(
        fileName: String,
        title: String,
        body: String
    ): ExportResult = withContext(Dispatchers.IO) {
        try {
            val file = File(exportDir(), "$fileName-${timestamp.format(Date())}.txt")
            file.writeText(
                buildString {
                    appendLine(title)
                    appendLine("Generated by GRC VANGUARD on ${readable.format(Date())}")
                    appendLine()
                    appendLine(body)
                    appendLine()
                    appendLine("Educational output. Verify against your own organisational records before relying on it.")
                }
            )
            ExportResult.Success(uriFor(file), file.name, "text/plain")
        } catch (e: Exception) {
            ExportResult.Failure(e.message ?: "Unable to write file")
        }
    }
}
